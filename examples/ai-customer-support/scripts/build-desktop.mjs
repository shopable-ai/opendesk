import { build } from 'esbuild';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root=resolve(import.meta.dirname,'..');
const desktop=join(root,'desktop');
await mkdir(desktop,{recursive:true});
const built=await build({entryPoints:[join(desktop,'core-entry.ts')],bundle:true,write:false,
  inject:[join(desktop,'history-clone.ts')],
  platform:'neutral',format:'iife',globalName:'OpenDeskSupportCore',target:'es2020',
  define:{'process.env.NODE_ENV':'"production"'},footer:{js:'globalThis.OpenDeskSupportCore = OpenDeskSupportCore;'},treeShaking:true,metafile:true,logLevel:'silent'});
await writeFile(join(desktop,'core.generated.js'),'// Generated by scripts/build-desktop.mjs from shared React reducer/domain.\n'+built.outputFiles[0].text);
const inputs={};
for(const file of Object.keys(built.metafile.inputs).sort()){
  if(file.includes('node_modules'))continue;
  inputs[file]=createHash('sha256').update(await readFile(resolve(file))).digest('hex');
}
await writeFile(join(desktop,'core-inputs.json'),JSON.stringify({schemaVersion:1,inputs},null,2)+'\n');
// Rasterize the same productArt SVGs used by React; no new illustration source.
if(process.argv.includes('--images')){
  if(process.platform!=='darwin')throw Error('--images requires macOS Quick Look; checked-in PNGs are portable');
  const catalogBuild=await build({entryPoints:[join(root,'src/domain/catalog.ts')],bundle:true,write:false,platform:'node',format:'esm'});
  const catalog=await import('data:text/javascript;base64,'+Buffer.from(catalogBuild.outputFiles[0].text).toString('base64'));
  const scratch=resolve(root,'../../.runtime/tests/ai-customer-support/image-build');
  const assets=join(desktop,'assets');await mkdir(scratch,{recursive:true});await mkdir(assets,{recursive:true});
  for(const p of catalog.products)for(const [i,image] of p.images.entries()){
    const name=p.id+'-'+image.id,svg=join(scratch,name+'.svg');
    await writeFile(svg,decodeURIComponent(catalog.productArt(p,i).split(',').slice(1).join(',')));
    execFileSync('/usr/bin/qlmanage',['-t','-s','640','-o',scratch,svg],{stdio:'pipe'});
    const png=await readFile(svg+'.png');await writeFile(join(assets,name+'.png'),png);
  }
}
console.log('Desktop shared core built; all four fixtures included.');
